"""Writes tests/locales.ts, the locale files as a module the mod tests can import (they cannot read files).

usage: /usr/bin/python3 tests/locale_fixture.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCALES = os.path.join(ROOT, "src", "side_insights", "locales")
TARGET = os.path.join(ROOT, "tests", "locales.ts")
LANGS = ("en", "ko", "ja")


def load(lang):
    with open(os.path.join(LOCALES, f"{lang}.json"), encoding="utf-8") as fh:
        return json.load(fh)


def render():
    body = ",\n".join(f"  {lang}: {json.dumps(load(lang), ensure_ascii=False, sort_keys=True)}" for lang in LANGS)
    return ("// Generated by tests/locale_fixture.py from src/side_insights/locales. Do not edit.\n"
            f"export const LOCALES: Record<'en' | 'ko' | 'ja', Record<string, string>> = {{\n{body},\n}}\n")


if __name__ == "__main__":
    with open(TARGET, "w", encoding="utf-8") as fh:
        fh.write(render())
